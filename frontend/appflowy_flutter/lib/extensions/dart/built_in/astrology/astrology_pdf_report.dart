          '${placement.name}${placement.retrograde ? ' (R)' : ''}',
          formatZodiacLongitude(placement.longitude),
          zodiacNames[placement.sign],
          '${placement.nakshatra} ${placement.pada}',
          nakshatraLord(nakshatraIndex(placement.longitude)).label,
          '${_house(placement.longitude)}',
          zodiacShortNames[divisionalSign(placement.longitude, 9)],
          placement.body == null ? '' : placement.speed.toStringAsFixed(4),
          karaka,
        ];
    return _table(
      [
        'Graha',
        'Longitude',
        'Sign',
        'Nakshatra pada',
        'Nak. lord',
        'House',
        'D-9',
        '°/day',
        'Karaka',
      ],
      [
        row(chart.lagna),
        for (final planet in chart.planets)
          row(
            planet,
            karaka: karakas.forBody(planet.body)?.abbreviation ?? '',
          ),
      ],
      widths: const {
        0: pw.FlexColumnWidth(1.4),
        1: pw.FlexColumnWidth(1.4),
        2: pw.FlexColumnWidth(1.1),
        3: pw.FlexColumnWidth(1.7),
        4: pw.FlexColumnWidth(),
        5: pw.FlexColumnWidth(0.6),
        6: pw.FlexColumnWidth(0.5),
        7: pw.FlexColumnWidth(0.9),
        8: pw.FlexColumnWidth(0.8),
