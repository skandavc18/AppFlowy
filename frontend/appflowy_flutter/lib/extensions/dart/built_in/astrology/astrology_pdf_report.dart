/// Bundled fonts: Inter carries the degree/prime/arrow signs, Poppins adds
/// Devanagari for names. Nothing is downloaded while printing.
class AstrologyPdfFonts {
  const AstrologyPdfFonts({
    required this.base,
    required this.bold,
    this.fallback = const [],
  });

  final pw.Font base;
  final pw.Font bold;
  final List<pw.Font> fallback;

  static Future<AstrologyPdfFonts> load() async {
    Future<pw.Font> font(String asset) async =>
        pw.Font.ttf(await rootBundle.load(asset));
    final inter = await font('assets/google_fonts/Inter/Inter-Variable.ttf');
    final poppins =
        await font('assets/google_fonts/Poppins/Poppins-Regular.ttf');
    final bold = await font('assets/google_fonts/Poppins/Poppins-SemiBold.ttf');
    return AstrologyPdfFonts(
      base: inter,
      bold: bold,
      fallback: [inter, poppins],
    );
  }
}

// Warm, print-friendly inks (the app's paper palette, not screen colors).
final _ink = PdfColor.fromInt(0xFF2B2824);
final _muted = PdfColor.fromInt(0xFF6E665B);
final _accent = PdfColor.fromInt(0xFF8A5A1F);
final _line = PdfColor.fromInt(0xFFD8CFC0);
final _fill = PdfColor.fromInt(0xFFF6F1E7);

const _divisions = [1, 2, 3, 4, 7, 9, 10, 12, 30];

/// A complete, self-contained report of [chart]: birth data, D-1/D-9 charts,
/// panchanga, positions, special lagnas and points, vargas, Vimshottari,
/// Shadbala and Ashtakavarga. Pure layout: every value comes from [chart].
Future<Uint8List> buildAstrologyPdf({
  required AstrologyChart chart,
  required AstrologyPdfFonts fonts,
  DateTime? generatedAt,
}) {
  final input = chart.input;
  final created = (generatedAt ?? DateTime.now()).toUtc();
  final name = input.name.trim().isEmpty ? 'Horoscope' : input.name.trim();
  final base = pw.ThemeData.withFont(
    base: fonts.base,
    bold: fonts.bold,
    fontFallback: fonts.fallback,
  );
  final theme = base.copyWith(
    defaultTextStyle: base.defaultTextStyle.copyWith(
      fontSize: 8.5,
      color: _ink,
    ),
  );
  final document = pw.Document(
    title: '$name · Vedic horoscope',
    author: 'AppFlowy',
    creator: 'AppFlowy Vedic astrology',
    subject: 'Vedic horoscope',
  );
  final report = _Report(chart, created);
  document.addPage(
    pw.MultiPage(
      pageTheme: pw.PageTheme(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.fromLTRB(34, 30, 34, 34),
        theme: theme,
      ),
      maxPages: 40,
      footer: (context) => pw.Container(
        margin: const pw.EdgeInsets.only(top: 8),
        child: pw.Row(
          children: [
            pw.Expanded(
              child: pw.Text(
                '$name · ${input.ayanamsaLabel} · '
                'Swiss Ephemeris ${chart.ephemerisVersion.isEmpty ? '' : chart.ephemerisVersion} '
                '· generated by AppFlowy',
                style: pw.TextStyle(fontSize: 7, color: _muted),
              ),
            ),
            pw.Text(
              'Page ${context.pageNumber} of ${context.pagesCount}',
              style: pw.TextStyle(fontSize: 7, color: _muted),
            ),
          ],
        ),
      ),
      build: (_) => report.build(name),
    ),
  );
  return document.save();
}

