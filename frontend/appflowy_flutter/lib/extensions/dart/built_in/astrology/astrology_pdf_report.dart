  String _moment(DateTime utc, {bool seconds = true}) =>
      '${astrologyLocalDate(input, utc)} '
      '${astrologyLocalClock(input, utc, seconds: seconds)}';

  String _date(DateTime utc) => astrologyLocalDate(input, utc);

  String _dms(double value, String positive, String negative) {
    final seconds = (value.abs() * 3600).round();
    return '${seconds ~/ 3600}°${_two(seconds ~/ 60 % 60)}′'
        '${_two(seconds % 60)}″ ${value < 0 ? negative : positive}';
  }

  List<(String, String)> _birthFacts() {
    final place = input.place;
    final offset = AstrologyTime.offsetAt(input, chart.utc);
    final local = AstrologyTime.localTime(input, chart.utc);
    final zone = place?.timeZone ?? '';
    String? solar(DateTime? time) =>
        time == null ? null : astrologyLocalClock(input, time, seconds: true);
    return [
      (
        'Birth date',
        '${_date(chart.utc)} · ${weekdayNames[local.weekday % 7]}',
      ),
      (
        'Birth time',
        '${astrologyLocalClock(input, chart.utc, seconds: true)} '
            '(${astrologyOffsetLabel(offset)})',
      ),
      (
        'Universal time',
        '${chart.utc.toIso8601String().substring(0, 19).replaceFirst('T', ' ')} UTC',
      ),
      ('Place', place == null || place.name.isEmpty ? '—' : place.name),
      (
        'Coordinates',
        place == null
            ? '—'
            : '${_dms(place.latitude, 'N', 'S')} · '
                '${_dms(place.longitude, 'E', 'W')}',
      ),
      (
        'Time zone',
        input.utcOffsetMinutes != null
            ? 'Fixed offset ${astrologyOffsetLabel(offset)}'
            : zone.isEmpty
                ? 'Device time zone'
                : zone,
      ),
      (
        'Ayanamsha',
        '${input.ayanamsaLabel} · '
            '${_dms(chart.ayanamsaDegrees, '', '−').trim()}',
      ),
      ('Rahu / Ketu', input.trueNode ? 'True node' : 'Mean node'),
      ('Dasha year', '${input.dashaYearDays} days'),
      (
        'Sunrise / sunset',
        solar(chart.sunrise) == null
            ? 'Unavailable (polar day or night)'
            : '${solar(chart.sunrise)} / ${solar(chart.sunset)}',
      ),
      ('Julian day (UT)', chart.julianDay.toStringAsFixed(6)),
      (
        'Ephemeris',
        chart.ephemerisVersion.isEmpty
            ? 'Swiss Ephemeris'
            : 'Swiss Ephemeris ${chart.ephemerisVersion}',
      ),
    ];
  }

  List<(String, String)> _panchangaFacts() {
    final moon = chart.planet(VedicBody.moon);
    final sun = chart.planet(VedicBody.sun);
    final nakshatra = nakshatraIndex(moon.longitude);
    final halfTithi = (chart.elongation / 6).floor();
    final first = periods.first;
    final balance = first.end.difference(chart.utc).inMicroseconds /
        (input.dashaYearDays * Duration.microsecondsPerDay);
    final hora = horaAt(chart);
    return [
      (
        'Vara',
        '${weekdayNames[chart.weekday]} (lord '
            '${weekdayLords[chart.weekday].label})'
            '${chart.sunrise == null ? ' · civil weekday' : ''}',
      ),
      (
        'Tithi',
        '${pakshaName(chart.tithi)} ${tithiName(chart.tithi)} '
            '(${chart.tithi}/30) · '
            '${(chart.tithiRemaining * 100).toStringAsFixed(1)}% remaining',
      ),
      (
        'Nakshatra',
        '${nakshatraNames[nakshatra]} pada ${moon.pada} · lord '
            '${nakshatraLord(nakshatra).label}',
      ),
      ('Yoga', '${yogaNames[chart.yoga]} (${chart.yoga + 1}/27)'),
      ('Karana', karanaName(halfTithi)),
      (
        'Hora lord',
        hora == null
            ? 'Unavailable'
            : '${hora.lord.label} (hora ${hora.number})',
      ),
      (
        'Lagna',
        '${zodiacNames[lagnaSign]} · ${formatZodiacLongitude(chart.ascendant)}',
      ),
      (
        'Moon sign',
        '${zodiacNames[moon.sign]} · lord ${signLords[moon.sign].label}'
      ),
      ('Sun sign', zodiacNames[sun.sign]),
      (
        'Dasha balance',
        '${first.lord.label} · ${balance.toStringAsFixed(4)} years '
            '(${_date(first.end)})',
      ),
    ];
  }

