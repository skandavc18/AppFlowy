  pw.Widget _note(String text) => pw.Padding(
        padding: const pw.EdgeInsets.only(top: 3),
        child: pw.Text(text, style: pw.TextStyle(fontSize: 7, color: _muted)),
      );

  pw.Widget _facts(List<(String, String)> facts) {
    final rows = <pw.TableRow>[];
    for (var i = 0; i < facts.length; i += 2) {
      final pair = [facts[i], if (i + 1 < facts.length) facts[i + 1]];
      rows.add(
        pw.TableRow(
          children: [
            for (final fact in pair) ...[
              _cell(fact.$1, color: _muted),
              _cell(fact.$2),
            ],
            if (pair.length == 1) ...[pw.SizedBox(), pw.SizedBox()],
          ],
        ),
      );
    }
    return pw.Table(
      border: pw.TableBorder(
        horizontalInside: pw.BorderSide(color: _line, width: 0.5),
        top: pw.BorderSide(color: _line, width: 0.5),
        bottom: pw.BorderSide(color: _line, width: 0.5),
      ),
      columnWidths: const {
        0: pw.FlexColumnWidth(1.1),
        1: pw.FlexColumnWidth(2.2),
        2: pw.FlexColumnWidth(1.1),
        3: pw.FlexColumnWidth(2.2),
      },
      children: rows,
    );
  }

  pw.Widget _cell(String text, {PdfColor? color}) => pw.Padding(
        padding: const pw.EdgeInsets.symmetric(horizontal: 3, vertical: 2.5),
        child: pw.Text(text, style: pw.TextStyle(color: color ?? _ink)),
      );

  pw.Widget _table(
    List<String> headers,
    List<List<String>> rows, {
    Map<int, pw.TableColumnWidth>? widths,
    Set<int> numeric = const {},
    double fontSize = 8,
  }) =>
      pw.TableHelper.fromTextArray(
        headers: headers,
        data: rows,
        border: pw.TableBorder.all(color: _line, width: 0.5),
        headerDecoration: pw.BoxDecoration(color: _fill),
        headerStyle: pw.TextStyle(
          fontSize: fontSize,
          fontWeight: pw.FontWeight.bold,
          color: _ink,
        ),
        cellStyle: pw.TextStyle(fontSize: fontSize, color: _ink),
        headerAlignment: pw.Alignment.centerLeft,
        cellAlignment: pw.Alignment.centerLeft,
        headerAlignments: {
          for (final index in numeric) index: pw.Alignment.centerRight,
        },
        cellAlignments: {
          for (final index in numeric) index: pw.Alignment.centerRight,
        },
        cellPadding: const pw.EdgeInsets.symmetric(horizontal: 3, vertical: 2),
        headerPadding:
            const pw.EdgeInsets.symmetric(horizontal: 3, vertical: 2.5),
        columnWidths: widths,
      );

